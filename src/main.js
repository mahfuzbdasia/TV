import './style.css';
import Hls from 'hls.js';

const app = document.querySelector('#app');
const API_BASE = (import.meta.env.VITE_API_BASE_URL || '').replace(/\/$/, '');
const TOKEN_KEY = 'mtv_device_token';
const PIN_KEY = 'mahfuz-tv-pin';
let channels = [];
let selectedCountry = 'All countries';
let searchTerm = '';
let activePlayer = null;
let refreshTimer = null;

const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const token = () => localStorage.getItem(TOKEN_KEY);
const pin = () => localStorage.getItem(PIN_KEY);

function pinScreen() {
  const setup = !pin();
  app.innerHTML = `<main class="center-screen"><div class="brand">M<span>TV</span></div><h1>Mahfuz TV</h1><p>${setup?'Create your local 4–8 digit app PIN':'Enter your PIN'}</p><form id="pin-form"><input id="pin" type="password" inputmode="numeric" pattern="[0-9]{4,8}" minlength="4" maxlength="8" placeholder="••••" autocomplete="off" required><button class="primary">${setup?'Set PIN':'Unlock'}</button><small id="pin-error"></small></form><p class="hint">PIN protects this app screen locally. Server access is separately protected by device activation.</p></main>`;
  document.querySelector('#pin').focus();
  document.querySelector('#pin-form').onsubmit = e => {
    e.preventDefault(); const entered = document.querySelector('#pin').value;
    if (setup) { localStorage.setItem(PIN_KEY, entered); activationScreen(); }
    else if (entered === pin()) { token() ? loadHome() : activationScreen(); }
    else document.querySelector('#pin-error').textContent = 'Incorrect PIN.';
  };
}
function activationScreen() {
  app.innerHTML = `<main class="center-screen"><div class="brand">M<span>TV</span></div><h1>Activate this device</h1><p>Enter the one-time code generated by your Mahfuz TV admin endpoint.</p><form id="activate-form"><input id="device-name" maxlength="80" placeholder="Device name (e.g. Living room TV)" value="${esc(localStorage.getItem('mtv_device_name')||'Mahfuz TV device')}"><input id="activation-code" maxlength="10" autocapitalize="characters" placeholder="10-character code" required><button class="primary">Activate device</button><small id="activation-error"></small></form><p class="hint">The activation code can be used once and expires in 15 minutes. This device token is saved locally so you do not need to activate again unless its access is revoked or app data is cleared.</p></main>`;
  document.querySelector('#activation-code').focus();
  document.querySelector('#activate-form').onsubmit = async e => {
    e.preventDefault();
    const button=e.submitter; button.disabled=true; button.textContent='Activating…';
    try {
      const response=await fetch(`${API_BASE}/api/activate`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({code:document.querySelector('#activation-code').value.trim().toUpperCase(),deviceName:document.querySelector('#device-name').value.trim()||'Mahfuz TV device'})});
      const data=await response.json();
      if(!response.ok) throw new Error(data.error||'Activation failed');
      localStorage.setItem(TOKEN_KEY,data.token);
      localStorage.setItem('mtv_device_name',document.querySelector('#device-name').value.trim());
      await loadHome();
    } catch(err) { document.querySelector('#activation-error').textContent=err.message; }
    finally { button.disabled=false; button.textContent='Activate device'; }
  };
}
async function fetchChannels() {
  const response=await fetch(`${API_BASE}/api/channels`,{headers:{Authorization:`Bearer ${token()}`},cache:'no-store'});
  const data=await response.json();
  if(response.status===401){localStorage.removeItem(TOKEN_KEY);activationScreen();throw new Error('Device authorization was revoked. Activate again.');}
  if(!response.ok) throw new Error(data.error||'Unable to load channels.');
  channels=data.channels||[];
  return data;
}
async function loadHome() {
  app.innerHTML='<main class="loading"><div class="brand">M<span>TV</span></div><p>Loading your private channel list…</p></main>';
  try {
    const data=await fetchChannels();
    renderHome(data.updatedAt);
    if(refreshTimer)clearInterval(refreshTimer);
    refreshTimer=setInterval(async()=>{try{const next=await fetchChannels();channels=next.channels||[];renderHome(next.updatedAt,true);}catch(e){console.warn(e);}},300000);
  } catch(e) {
    if(!token()) return;
    app.innerHTML=`<main class="center-screen"><div class="brand">M<span>TV</span></div><h1>Channels unavailable</h1><p>${esc(e.message)}</p><button class="primary" id="retry">Try again</button><button class="secondary" id="lock">Lock app</button></main>`;
    document.querySelector('#retry').onclick=loadHome;document.querySelector('#lock').onclick=()=>{clearInterval(refreshTimer);pinScreen();};
  }
}
function renderHome(updatedAt, preserveScroll=false) {
  const scroll=window.scrollY;
  const countries=['All countries',...new Set(channels.map(c=>c.country).filter(Boolean).sort((a,b)=>a.localeCompare(b)))];
  const filtered=channels.filter(c=>(selectedCountry==='All countries'||c.country===selectedCountry)&&`${c.title} ${c.country}`.toLowerCase().includes(searchTerm.toLowerCase()));
  app.innerHTML=`<div class="layout"><aside class="sidebar"><div class="brand">M<span>TV</span></div><div class="side-label">LIBRARY</div><button class="side-link active" id="all-channels">▣ <span>Live TV</span></button><button class="side-link" id="refresh">↻ <span>Refresh list</span></button><button class="side-link" id="lock">⌑ <span>Lock app</span></button><div class="side-note">PRIVATE CHANNEL LIBRARY</div></aside><main class="main"><header class="top"><div><div class="eyebrow">YOUR PERSONAL STREAMING SPACE</div><h1>Mahfuz <span>TV</span></h1></div><div class="status">● PRIVATE SYNC</div></header><section class="hero"><div class="eyebrow red">YOUR CHANNELS, YOUR SCREEN</div><h2>Live TV.<br>One place.</h2><p>Private channel library • Updates from your Drive CSV</p><div class="hero-meta"><span>${channels.length.toLocaleString()} channels</span><span>Synced ${updatedAt?new Date(updatedAt).toLocaleTimeString(): 'just now'}</span></div></section><section class="toolbar"><div><h2>Live TV Channels</h2><p>Choose a channel to start streaming.</p></div><input id="search" type="search" placeholder="Search channels…" value="${esc(searchTerm)}"></section><div class="filters"><select id="country">${countries.map(c=>`<option ${c===selectedCountry?'selected':''}>${esc(c)}</option>`).join('')}</select><span>${filtered.length.toLocaleString()} results</span></div><section class="grid">${filtered.map((c,i)=>`<button class="channel" data-id="${esc(c.id)}" style="--hue:${(i*41)%360}"><span class="channel-art"><span class="channel-initial">${esc((c.title||'TV').slice(0,2).toUpperCase())}</span><span class="live">LIVE</span></span><span class="channel-name">${esc(c.title)}</span><span class="channel-country">${esc(c.country||'Unknown')}</span></button>`).join('')||'<div class="empty">No channels match this search.</div>'}</section><footer>Mahfuz TV <span>Use only streams you are authorized to access.</span></footer></main></div><div id="player" class="player" hidden><button id="close-player" class="close">×</button><div id="player-inner"></div></div>`;
  document.querySelector('#search').oninput=e=>{searchTerm=e.target.value;const pos=window.scrollY;renderHome(updatedAt);window.scrollTo(0,pos);const input=document.querySelector('#search');input.focus();input.setSelectionRange(searchTerm.length,searchTerm.length);};
  document.querySelector('#country').onchange=e=>{selectedCountry=e.target.value;renderHome(updatedAt);};
  document.querySelector('#refresh').onclick=loadHome;
  document.querySelector('#all-channels').onclick=()=>{selectedCountry='All countries';searchTerm='';renderHome(updatedAt);};
  document.querySelector('#lock').onclick=()=>{clearInterval(refreshTimer);pinScreen();};
  document.querySelectorAll('[data-id]').forEach(b=>b.onclick=()=>playChannel(channels.find(c=>c.id===b.dataset.id)));
  document.querySelector('#close-player').onclick=closePlayer;
  if(preserveScroll)window.scrollTo(0,scroll);
}
function playChannel(channel) {
  if(!channel)return;
  closePlayer(false);
  const player=document.querySelector('#player'), inner=document.querySelector('#player-inner');
  player.hidden=false;
  inner.innerHTML=`<div class="player-head"><div><strong>${esc(channel.title)}</strong><span>${esc(channel.country)}</span></div><span class="live">LIVE</span></div><video id="video" controls autoplay playsinline></video><p id="play-error" class="play-error"></p>`;
  const video=document.querySelector('#video'); activePlayer={video,hls:null};
  const url=channel.url;
  if(/\.m3u8($|\?)/i.test(url)&&Hls.isSupported()) {
    const hls=new Hls({enableWorker:false,lowLatencyMode:false}); activePlayer.hls=hls;hls.loadSource(url);hls.attachMedia(video);
    hls.on(Hls.Events.ERROR,(_event,data)=>{if(data.fatal)document.querySelector('#play-error').textContent='Stream playback failed. The stream may be offline or block browser playback.';});
  } else {
    video.src=url;
    video.onerror=()=>{const err=document.querySelector('#play-error');if(err)err.textContent='Could not play this stream. The URL may be offline, unsupported, or blocked by CORS.';};
  }
  video.play().catch(()=>{});
}
function closePlayer(repaint=true) {
  if(activePlayer?.hls)activePlayer.hls.destroy();
  if(activePlayer?.video){activePlayer.video.pause();activePlayer.video.removeAttribute('src');activePlayer.video.load();}
  activePlayer=null;
  const p=document.querySelector('#player');if(p)p.hidden=true;
  const inner=document.querySelector('#player-inner');if(inner)inner.innerHTML='';
}
document.addEventListener('keydown',e=>{if(e.key==='Escape')closePlayer();});
if(!pin())pinScreen();else if(token())loadHome();else pinScreen();
